/// On macOS these builds replace a generic mod: (generic, mac build). The same pair as srl-mods'
/// `MAC_REPLACES` (resolve.rs): there the `mac-only` Sodium Mac takes Sodium's place in a resolved
/// set, so looking up `sodium` in a macOS set finds nothing.
pub const MAC_REPLACES: [(&str, &str); 1] = [("sodium", "sodiummac")];

impl PracticeProfile {
    /// Every mod id the instance gets on this OS: `mods`, plus `accessibility` when asked for,
    /// with the macOS builds swapped in when `macos`.
    pub fn mod_ids(&self, accessibility: bool, macos: bool) -> Vec<&'static str> {
        let extra = if accessibility {
            self.accessibility
        } else {
            &[]
        };
        self.mods
            .iter()
            .chain(extra)
            .map(|m| {
                MAC_REPLACES
                    .iter()
                    .find(|(generic, _)| macos && *generic == m.id)
                    .map_or(m.id, |(_, mac)| mac)
            })
            .collect()
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashSet;

    #[test]
    fn lists_are_disjoint_and_have_no_world_makers() {
        let p = PRACTICE;
        let all: HashSet<_> = p.mod_ids(true, false).into_iter().collect();
        assert_eq!(all.len(), p.mod_ids(true, false).len(), "duplicates");
        for m in p.excluded {
            assert!(!all.contains(m.id), "{} is both in and out", m.id);
        }
        for id in ["atum", "seedqueue", "fast_reset", "standardsettings"] {
            assert!(!all.contains(id), "{id} resets or rewrites worlds");
        }
        assert!(all.contains("speedrunigt"));
        assert_eq!(p.minecraft_version, crate::catalogue::PRACTICE_MINECRAFT);
    }

    #[test]
    fn macos_gets_sodium_mac() {
        let mac = PRACTICE.mod_ids(false, true);
        assert!(mac.contains(&"sodiummac") && !mac.contains(&"sodium"));
        assert_eq!(mac.len(), PRACTICE.mod_ids(false, false).len());
        let other = PRACTICE.mod_ids(false, false);
        assert!(other.contains(&"sodium") && !other.contains(&"sodiummac"));
    }

    /// Every id must be an mcsr-meta modid with a 1.16.1 build. Uses srl-mods' trimmed copy of
    /// mods.json when it is there (the test is skipped otherwise, so a fixture change elsewhere
    /// can't break this crate).
    #[test]
    fn ids_exist_in_mcsr_meta() {
        let path = concat!(
            env!("CARGO_MANIFEST_DIR"),
            "/../srl-mods/tests/fixtures/meta/mods.json"
        );
        let Ok(json) = std::fs::read_to_string(path) else {
            eprintln!("skipped: no {path}");
            return;
        };
        let v: serde_json::Value = serde_json::from_str(&json).unwrap();
        let known: HashSet<String> = v["mods"]
            .as_array()
            .unwrap()
            .iter()
            .filter(|m| {
                m["versions"].as_array().is_some_and(|vs| {
                    vs.iter().any(|v| {
                        v["target_version"]
                            .as_array()
                            .is_some_and(|t| t.iter().any(|t| t == "1.16.1"))
                    })
                })
            })
            .map(|m| m["modid"].as_str().unwrap().to_string())
            .collect();
        for macos in [false, true] {
            for id in PRACTICE.mod_ids(true, macos) {
                assert!(known.contains(id), "{id} is not a 1.16.1 mod in mcsr-meta");
            }
        }
        // Optional mods the catalogue names but the launcher doesn't provide: still not in
        // mcsr-meta (if one arrives, consider adding it to the profile).
        for id in ["carpet", "autocraftable", "playerattribute"] {
            assert!(!known.contains(id), "{id} is in mcsr-meta now");
        }
        for m in PRACTICE.excluded {
            assert!(
                known.contains(m.id),
                "excluded {} is not in mcsr-meta",
                m.id
            );
        }
    }
}
