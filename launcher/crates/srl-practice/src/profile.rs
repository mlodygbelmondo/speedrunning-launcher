//! The practice instance: what it runs and which mods it gets. The integration after M2 hands this
//! to srl-game (Minecraft, Fabric, Java) and srl-mods (the mods, picked from mcsr-meta by modid),
//! with `Paths::practice_instance()` as the game directory.
//!
//! **Why these mods.** Practice should feel like a run, so the instance gets the same performance
//! and fix mods the run setups have, plus SpeedRunIGT for the timer. It must not get anything
//! that makes or resets worlds on its own: on a practice map that would throw the player out of
//! the map (Atum, SeedQueue), skip saving their progress (FastReset), or apply a run's standard
//! options over theirs (StandardSettings). None of the 13 installable maps needs a mod
//! (research/04 §1.1 and the authors' READMEs, checked 2026-10-26). Some use one optionally:
//! Zero Sorting's hunger and health reset needs `playerattribute`, LBP (also bundled in The MCSR
//! Practice Map) uses Carpet for saturation resetting, and OW Practice v2.0 suggests
//! AutoCraftable. None of them is in mcsr-meta, so none is in the set; the catalogue lists them as
//! optional requirements the launcher doesn't provide.

/// The mod loader. Only Fabric for now; the type says so explicitly so a second loader can't be
/// assumed by accident.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Loader {
    Fabric,
}

/// A mod by its mcsr-meta `modid`, with the reason it is in (or out of) the set.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct ProfileMod {
    pub id: &'static str,
    pub why: &'static str,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct PracticeProfile {
    pub minecraft_version: &'static str,
    pub loader: Loader,
    /// The oldest Fabric Loader the set accepts (the same floor as the 1.16.1 modes).
    pub min_fabric_loader: &'static str,
    /// Java major version (the same runtime as the 1.16.1 modes, Mojang's `java-runtime-delta`).
    pub java_major: u32,
    /// Always installed, on every OS, by generic id. On macOS [`PracticeProfile::mod_ids`] gives
    /// Sodium Mac instead of Sodium ([`MAC_REPLACES`]), as srl-mods' resolve does for the modes.
    pub mods: &'static [ProfileMod],
    /// Installed when the player turned on the accessibility option in Settings, as for modes.
    pub accessibility: &'static [ProfileMod],
    /// Deliberately left out, with the reason. A test checks no id is in both lists.
    pub excluded: &'static [ProfileMod],
    /// For the integration and the UI.
    pub notes: &'static [&'static str],
}

